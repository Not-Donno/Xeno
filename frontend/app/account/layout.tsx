export default function AccountLayout({ children }: { children: React.ReactNode }) {
  const { user, loading } = useAuth();
  const pathname = usePathname();
  const router = useRouter();

  useEffect(() => {
    if (!loading && !user) {
      router.push('/auth/login');
    }
  }, [user, loading, router]);

  if (loading) {
    return (
      <div className="container-x py-12">
        <div className="flex gap-8">
          <div className="w-56 space-y-3">
            {Array.from({ length: 6 }).map((_, i) => (
              <div key={i} className="h-10 bg-surface-light rounded-lg animate-pulse" />
            ))}
          </div>
          <div className="flex-1 space-y-4">
            <div className="h-8 w-48 bg-surface-light rounded animate-pulse" />
            <div className="h-64 bg-surface-light rounded-xl animate-pulse" />
          </div>
        </div>
      </div>
    );
  }

  if (!user) return null;

  return (
    <div className="container-x py-8 md:py-12">
      <div className="flex flex-col md:flex-row gap-8">
        {/* Sidebar */}
        <aside className="w-full md:w-56 shrink-0">
          <div className="card p-4">
            <div className="flex items-center gap-3 mb-6 pb-4 border-b border-surface-border">
              <div className="w-10 h-10 rounded-full bg-gradient-to-br from-accent to-cosmic-500 flex items-center justify-center text-sm font-bold text-white">
                {user.firstName[0]}
                {user.lastName[0]}
              </div>
              <div>
                <p className="text-sm font-medium text-star-white">{user.firstName} {user.lastName}</p>
                <p className="text-xs text-star-blue/50">{user.email}</p>
              </div>
            </div>
            <nav className="space-y-1">
              {navItems.map((item) => {
                const isActive = pathname === item.href;
                return (
                  <Link
                    key={item.href}
                    href={item.href}
                    className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-all duration-300 ${
                      isActive
                        ? 'bg-accent/10 text-accent font-medium'
                        : 'text-star-blue/60 hover:text-star-white hover:bg-surface-light/50'
                    }`}
                  >
                    <svg className="w-4.5 h-4.5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                      <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d={item.icon} />
                    </svg>
                    {item.label}
                  </Link>
                );
              })}
            </nav>
          </div>
        </aside>

        {/* Main Content */}
        <main className="flex-1 min-w-0">{children}</main>
      </div>
    </div>
  );
}
